export type WorkSort = "new" | "top";
export const WORK_SORTS = ["new", "top"] as const satisfies readonly WorkSort[];
/** The lists app/api/communities/[handle]/[list] answers; a community's prompts are GET /api/marketplace/prompts?community=. */
export const COMMUNITY_LISTS = ["works", "members", "showroom"] as const;
export type CommunityList = (typeof COMMUNITY_LISTS)[number];

export interface CommunityInput {
  name: string;
  /** Without one, the slug of the name. */
  handle?: string;
  description?: string | null;
  /** After a 409 CLOSE_MATCHES the dialog sends it again with this: made anyway. */
  confirmed?: boolean;
}
/** An absent field stays; null clears the description; aliases replace the list (up to MAX_ALIASES). */
export interface CommunityPatch {
  name?: string;
  description?: string | null;
  aliases?: string[];
}
/** Sets the communities of up to MAX_LINK_AT_ONCE items the caller owns, each to this whole list (its prompt's
 *  included: one left out is opted out of; one put back is in again). Up to MAX_COMMUNITIES_PER_WORK. */
export interface LinksInput {
  kind: ItemKind;
  ids: string[];
  communityIds: string[];
}
export interface SuggestInput {
  /** The words the surface holds: the bar's prompt, the editor's title and text, a post's title and caption. */
  text: string;
  /** Already picked: never suggested. */
  exclude?: string[];
}
export interface PostInput {
  /** One of the caller's own public renders, not posted before. */
  imageId: string;
  title: string;
  caption?: string | null;
  /** 1 to MAX_COMMUNITIES_PER_WORK. An answer takes its parent's communities and ignores these: variations live under
   *  the post they answer, in every community it is in. */
  communityIds?: string[];
  /** Answers that post with the caller's own version. Answers are one level deep: answering an answer answers its
   *  parent. */
  parentId?: string | null;
}
export type MergeInput = { from: string; into: string } | { keep: string[] };
export interface HideInput {
  kind: ItemKind;
  id: string;
  hidden: boolean;
}

/** The responses, by route (status 200 unless said). Every failure is { error: <one sentence below> }, with the
 *  extra fields said here. A list's `next` is the cursor of its next page, null at its end. */
export interface CommunityResponses {
  /** ?q= (typeahead and the directory's search: listed and unlisted, ranked, one page) or ?sort=&cursor= (listed). */
  "GET /": { communities: CommunityCard[]; next: string | null };
  /** 201, its creator joined. 409 HANDLE_TAKEN with { existing: CommunityCard }; 409 CLOSE_MATCHES with
   *  { closest: CommunityCard[] } unless confirmed. */
  "POST /": { community: CommunityDetail };
  /** Or { redirect: <handle> }: a merged community's, or the canonical spelling of a look-alike. */
  "GET /[handle]": { community: CommunityDetail } | { redirect: string };
  "PATCH /[handle]": { community: CommunityDetail };
  /** Admins only (spam): the community, its links, members and search words, for good; its handle is free again.
   *  Works, prompts and posts stay where else they are. */
  "DELETE /[handle]": { deleted: true };
  "PUT /[handle]/membership": { joined: true; members: number };
  "DELETE /[handle]/membership": { joined: false; members: number };
  "GET /[handle]/works": { works: Work[]; next: string | null };
  "GET /[handle]/members": { members: Member[]; next: string | null };
  "GET /[handle]/showroom": { posts: ShowroomPost[]; next: string | null };
  "POST /[handle]/hide": { hidden: boolean };
  /** ?kind=&id= */
  "GET /links": ItemCommunities;
  /** One entry per id, in the order sent. */
  "PUT /links": { items: Array<{ id: string } & ItemCommunities> };
  "POST /suggest": { suggestions: CommunityChip[] };
  /** 201. 409 MAKE_PUBLIC_FIRST; 409 ALREADY_POSTED with { postId }. */
  "POST /posts": { post: ShowroomPost };
  "GET /posts/[id]": { post: ShowroomPost };
  "DELETE /posts/[id]": { deleted: true };
  "GET /merges": { groups: MergeGroup[] };
  "POST /merges": { merged: { from: string; into: string; links: number; members: number } } | { kept: number };
}

