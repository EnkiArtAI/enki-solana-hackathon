/* ── Rows, as SQL 54 makes them (snake_case; read by the routes only). ── */

export interface CommunityRow {
  id: string;
  handle: string;
  /** Generated by SQL 54 (community_key(handle)): separators gone, look-alike digits folded; unique over every row, a
   *  merged one's included, so a merged handle stays taken and redirects. */
  handle_key: string;
  /** lib/communities/handle.ts coreWord(handle): what the merge queue groups by. */
  core: string;
  name: string;
  description: string | null;
  /** Who started it (they may edit it); null once that account is gone. */
  created_by: string | null;
  /** Set when an admin merged it into another: its links and members moved there, its handle redirects there. */
  merged_into: string | null;
  merged_at: string | null;
  /** Set when an admin kept its core group apart ("keep"); a new community of the same core brings the group back. */
  core_reviewed_at: string | null;
  created_at: string;
  updated_at: string;
}
export interface CommunityAliasRow {
  community_id: string;
  /** Handle-shaped slug, "pepe_the_frog". */
  alias: string;
  /** Generated: community_key(alias). */
  alias_key: string;
  created_at: string;
}
export interface CommunityMemberRow {
  community_id: string;
  user_id: string;
  created_at: string;
}
/** shown: in the community. opted_out: its owner took a render out that its prompt brought in (images only).
 *  hidden: a moderator took it out; its owner cannot put it back. */
export type LinkState = "shown" | "opted_out" | "hidden";
export interface CommunityLinkRow {
  community_id: string;
  /** Exactly one of the three. */
  prompt_id: string | null;
  image_id: string | null;
  post_id: string | null;
  /** Who linked it: the item's owner; for a moderator's hidden row on an inherited render, the moderator. */
  user_id: string;
  state: LinkState;
  created_at: string;
}
export interface ShowroomPostRow {
  id: string;
  user_id: string;
  /** One of the poster's own renders (generated_images.id), never an upload; one post per render. */
  image_id: string;
  title: string;
  caption: string | null;
  /** The post this one answers with the poster's own version; null for a post of its own, or once that one is gone. */
  parent_id: string | null;
  created_at: string;
}
/** SQL 54's view community_cards: one row per live (unmerged) community. Counts leave 18+ works out. */
export interface CommunityCardRow {
  id: string;
  handle: string;
  handle_key: string;
  core: string;
  name: string;
  description: string | null;
  created_by: string | null;
  created_at: string;
  core_reviewed_at: string | null;
  members: number;
  works: number;
  works_7d: number;
  listed: boolean;
  /** The cover rule (agreed 2026-10-30, after Kev: "am besten das mit den meisten generierungen"): the first showcase
   *  image of its listed, non-18+ linked prompt with the most generations, else its most-liked work, else its newest;
   *  null with neither. */
  cover_url: string | null;
}
/** SQL 54's view community_works: every public render in a community, once each. In by a direct link, by a listed
 *  linked prompt it was made from (unless its owner opted out or a moderator hid it), or as a Showroom post's render. */
export interface CommunityWorkRow {
  community_id: string;
  image_id: string;
  user_id: string;
  prompt_id: string | null;
  mime_type: string | null;
  storage_url: string | null;
  preview_url: string | null;
  thumbnail_url: string | null;
  width: number | null;
  height: number | null;
  is_adult: boolean;
  like_count: number;
  /** When it came into the community: the latest of its link, its first going public and its making. */
  added_at: string;
}

/* ── What the API answers (camelCase). Times are ISO strings. ── */

/** A community as a chip (pickers, a work's list). */
export interface CommunityChip {
  id: string;
  handle: string;
  name: string;
}
/** A community as a directory card: equal portrait 3:4 cards, one cover each (Kev, 2026-10-30: "alle communities gleich
 *  große senkrechte karten ... von denen jeder ein bild bekommt"). */
export interface CommunityCard extends CommunityChip {
  members: number;
  works: number;
  works7d: number;
  /** Unlisted ones come only from a search or their link. */
  listed: boolean;
  cover: string | null;
}
/** GET /api/communities/[handle]. */
export interface CommunityDetail extends CommunityCard {
  description: string | null;
  aliases: string[];
  createdBy: { handle: string | null } | null;
  createdAt: string;
  /** For the viewer: a member; may edit (its creator, an admin); staff may hide (admin, mod) and merge (admin). */
  joined: boolean;
  canEdit: boolean;
  staff: "admin" | "mod" | null;
}
export type WorkKind = "image" | "video";
/** A render in a community's Works (and a post's picture). */
export interface Work {
  imageId: string;
  /** By its mime type: video/* is a video. */
  kind: WorkKind;
  /** Its detail rendition (preview, else the original). */
  url: string;
  /** Its small one (thumbnail, else url). */
  thumb: string;
  width: number | null;
  height: number | null;
  owner: { handle: string | null };
  /** The prompt it was made with, only while that prompt is listed: "Open its prompt". */
  promptId: string | null;
  likes: number;
  addedAt: string;
}
/** A Showroom post: one of its poster's own renders with a title (Kev, 2026-10-30: "people would also like to just
 *  create together and share artpieces they have done. so we might need some sort of a showroom, decoupled from
 *  prompts completely"). */
export interface ShowroomPost {
  id: string;
  title: string;
  caption: string | null;
  author: { handle: string | null };
  work: Work;
  communities: CommunityChip[];
  parentId: string | null;
  /** Answers (variations) it has. */
  answers: number;
  /** In a list: up to INLINE_ANSWERS newest answers; read alone: up to POST_ANSWERS. */
  latestAnswers: ShowroomPost[];
  mine: boolean;
  createdAt: string;
}
export interface Member {
  handle: string | null;
  /** Started the community. */
  creator: boolean;
  joinedAt: string;
}
/** GET /api/communities/links: the communities one item is in. */
export interface ItemCommunities {
  /** Where it shows: its own links and those its listed prompt brings (not opted out, not hidden). */
  communities: CommunityChip[];
  /** The ids among `communities` its prompt brings: × opts the render out of them. */
  inherited: string[];
  /** Its owner only (empty for anyone else): the prompt's communities it was taken out of, and those a moderator hid. */
  optedOut: CommunityChip[];
  hidden: CommunityChip[];
}
/** The merge queue: live communities sharing a core word, while one of them is not kept apart yet. */
export interface MergeGroup {
  core: string;
  communities: Array<CommunityCard & { createdAt: string; createdBy: string | null; reviewed: boolean }>;
}

